"""Build kaggle/explore_kernel/kernel.py (+ kernel-metadata.json) from pod/explore.py.

A Kaggle script kernel is one file, so we inline explore.py, drop its __main__ guard, and append
a wrapper that adds the same observability as the pod job: STAGE markers, a preflight on the mounted
data that fails fast, an RP_REPORT block that is printed on success AND failure, exit 1 on failure.
Usage: build_kernel.py USERNAME
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(__file__).resolve().parent / "explore_kernel"
SLUG = "gemma-4-graph-explore"

WRAPPER = """

# ---- Kaggle kernel wrapper (generated by kaggle/build_kernel.py) -------------------------------
import os  # noqa: E402
import time  # noqa: E402
import traceback  # noqa: E402

DATA = Path(os.environ.get("DATA_DIR", "/kaggle/input/competitions/gemma-4-developer-agent"))
OUTD = Path(os.environ.get("OUT_DIR", "/kaggle/working"))
MIN_FILES = int(os.environ.get("MIN_FILES", "100"))


def stage(name: str) -> None:
    print(f"STAGE {name} (t+{time.time() - T0:.0f}s)", flush=True)


def preflight() -> None:
    if not DATA.is_dir():
        root = Path("/kaggle/input")
        mounts = sorted(p.name for p in root.glob("*")) if root.is_dir() else []
        raise SystemExit(f"ERROR data dir {DATA} missing; /kaggle/input has {mounts}")
    top = sorted(p.name for p in DATA.iterdir())
    n_tasks = sum(1 for _ in open(DATA / "tasks.jsonl")) if (DATA / "tasks.jsonl").is_file() else 0
    n_g = len(list((DATA / "graphs").glob("*.json")))
    n_e = len(list((DATA / "embeddings").glob("*.npz")))
    print(f"data: top-level={top} tasks={n_tasks} graphs={n_g} embeddings={n_e}", flush=True)
    if n_tasks < 1:
        raise SystemExit("ERROR tasks.jsonl missing or empty")
    if n_g < MIN_FILES or n_e < MIN_FILES:
        raise SystemExit(f"ERROR too few files: graphs={n_g} embeddings={n_e} (< {MIN_FILES})")


def kernel_main() -> None:
    status, rc = "ok", 0
    try:
        stage("preflight")
        preflight()
        stage("analyze")
        OUTD.mkdir(parents=True, exist_ok=True)
        rc = __ENTRY__
        if rc != 0:
            raise SystemExit(f"ERROR explore returned {rc}")
        stage("done")
    except BaseException:
        status = "failed"
        traceback.print_exc()
        print("STAGE failed", flush=True)
    report = None
    try:
        report = json.loads((OUTD / "report.json").read_text())
    except Exception:
        pass
    print("RP_REPORT_BEGIN")
    print(json.dumps({"status": status, "report": report}, separators=(",", ":")))
    print("RP_REPORT_END", flush=True)
    if status != "ok":
        raise SystemExit(1)


T0 = time.time()
kernel_main()
"""


GUARD_RE = re.compile(r'\nif __name__ == "__main__":\n    raise SystemExit\(\w+\(sys\.argv\)\)\n?$')


def _inline(name: str) -> str:
    src = GUARD_RE.sub("\n", (ROOT / "pod" / name).read_text(encoding="utf-8"))
    assert "__main__" not in src, f"{name} main guard not stripped"
    return src


def build(username: str, kind: str = "explore") -> Path:
    global OUT, SLUG
    src = _inline("explore.py")
    entry = 'main(["x", str(DATA), str(OUTD)])'
    if kind == "audit":
        OUT = Path(__file__).resolve().parent / "audit_kernel"
        SLUG = "gemma-4-graph-audit"
        src += "\n" + _inline("audit.py").replace("from __future__ import annotations\n", "")
        entry = "audit_main()"
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "kernel.py").write_text(src + WRAPPER.replace("__ENTRY__", entry), encoding="utf-8")
    meta = {
        "id": f"{username}/{SLUG}",
        "title": "Gemma 4 Graph Explore" if SLUG.endswith("explore") else "Gemma 4 Graph Audit",
        "code_file": "kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "false",
        "enable_tpu": "false",
        "enable_internet": "false",
        "dataset_sources": [],
        "competition_sources": ["gemma-4-developer-agent"],
        "kernel_sources": [],
        "model_sources": [],
    }
    (OUT / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    return OUT / "kernel.py"


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "explore"))
